#!/usr/bin/env node
/**
 * generate-resource — 由资源声明生成：表迁移 + schema 规则 + 路由(GET/POST/PATCH/DELETE) +
 * server 注册 + 单表 RLS + 前端 CRUD 页(列表/新建/编辑/删除/状态快捷) + 菜单/路由。
 *
 * 用法： node tools/generate-resource.mjs <name> [--dir <projectRoot>]
 * 声明： resources/<name>.json
 * {
 *   "name": "tickets",
 *   "fields": [
 *     {"name":"title","type":"text"},
 *     {"name":"priority","type":"text","enum":["low","normal","high"]},
 *     {"name":"status","type":"text","enum":["open","pending","closed"]}
 *   ],
 *   "member": { "seeAll": false, "writable": ["title","priority","status"] }
 * }
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';

const SQL_TYPES = new Set(['text', 'numeric', 'boolean', 'int', 'bigint', 'timestamptz', 'uuid', 'jsonb']);
const RESERVED = new Set([
  'order', 'user', 'group', 'table', 'select', 'from', 'where', 'insert', 'update', 'delete',
  'join', 'limit', 'offset', 'primary', 'foreign', 'references', 'constraint', 'default', 'check',
  'unique', 'index', 'view', 'grant', 'role', 'case', 'when', 'then', 'else', 'end', 'and', 'or',
  'not', 'null', 'true', 'false', 'as', 'on', 'in', 'is', 'like', 'between', 'exists', 'all', 'any',
  'distinct', 'having', 'union', 'by', 'values', 'set', 'into', 'create', 'drop', 'alter', 'add',
  'column', 'transaction', 'begin', 'commit', 'rollback',
]);
function invalidName(s) {
  return !/^[a-z][a-z0-9_]*$/.test(s) || RESERVED.has(s);
}
function pascal(s) {
  return s.replace(/(^|[-_])(\w)/g, (_, __, c) => c.toUpperCase());
}
function nextNumber(dir) {
  const nums = readdirSync(dir)
    .map((f) => /^(\d{4})_/.exec(f)?.[1])
    .filter(Boolean)
    .map(Number);
  return String(Math.max(0, ...nums) + 1).padStart(4, '0');
}
function colSql(f) {
  const type = SQL_TYPES.has(f.type) ? f.type : 'text';
  let s = `  ${f.name} ${type}`;
  if (f.default !== undefined) s += ` not null default ${typeof f.default === 'string' ? `'${f.default}'` : f.default}`;
  else if (f.nullable === false) s += ' not null';
  return s;
}
function defaultSpec(name) {
  return {
    name,
    fields: [
      { name: 'title', type: 'text', required: true },
      { name: 'status', type: 'text', default: 'draft' },
    ],
    member: { seeAll: false, writable: ['title', 'status'] },
  };
}

function main() {
  const args = process.argv.slice(2);
  const di = args.indexOf('--dir');
  const projectRoot = resolve(di >= 0 ? args[di + 1] : '.');
  const name = args.find((a) => !a.startsWith('--') && a !== projectRoot);
  if (!name) {
    console.error('usage: generate-resource <name> [--dir <projectRoot>]');
    process.exit(1);
  }
  if (invalidName(name)) {
    console.error(`invalid resource name "${name}": 需为 snake_case、复数，且非 SQL 保留字（如用 orders 而非 order）`);
    process.exit(1);
  }
  const apiDir = join(projectRoot, 'api');
  const dbDir = join(projectRoot, 'db', 'migrations');
  if (!existsSync(apiDir) || !existsSync(dbDir)) {
    console.error(`not a derui-admin project (missing api/ or db/migrations/): ${projectRoot}`);
    process.exit(1);
  }

  const resDir = join(projectRoot, 'resources');
  const specPath = join(resDir, `${name}.json`);
  if (!existsSync(specPath)) {
    mkdirSync(resDir, { recursive: true });
    writeFileSync(specPath, JSON.stringify(defaultSpec(name), null, 2) + '\n', 'utf8');
    console.log(`spec template created: ${specPath}\nEdit it then re-run.`);
    process.exit(0);
  }
  const spec = JSON.parse(readFileSync(specPath, 'utf8'));
  const fields = spec.fields ?? [];
  const writable = spec.member?.writable ?? fields.map((f) => f.name);
  const seeAll = spec.member?.seeAll === true;
  const selectExpr = seeAll ? 'true' : "eqUser('owner_id')";
  const pascalName = pascal(name);
  const fn = `register${pascalName}`;
  const selCols = ['id', ...fields.map((f) => f.name), 'owner_id', 'version', 'created_at'];

  // 1) 表迁移
  const tNum = nextNumber(dbDir);
  const tableSql =
    `-- ${name} resource (generated by generate-resource)\n` +
    `create table public.${name} (\n` +
    `  id uuid primary key default gen_random_uuid(),\n` +
    `  tenant_id uuid not null references public.tenant(id) on delete restrict,\n` +
    `  version int not null default 1,\n` +
    fields.map(colSql).join(',\n') +
    (fields.length ? ',\n' : '') +
    `  owner_id uuid,\n` +
    `  created_at timestamptz not null default now(),\n` +
    `  updated_at timestamptz not null default now()\n` +
    `);\n\n` +
    `create index idx_${name}_tenant on public.${name}(tenant_id);\n\n` +
    `create trigger trg_${name}_updated before update on public.${name}\n` +
    `  for each row execute function public.set_updated_at();\n`;
  writeFileSync(join(dbDir, `${tNum}_${name}.sql`), tableSql, 'utf8');
  console.log(`migration: db/migrations/${tNum}_${name}.sql`);

  // 2) schema 规则（幂等）
  const schemaPath = join(apiDir, 'src', 'schema.ts');
  let schema = readFileSync(schemaPath, 'utf8');
  if (new RegExp(`\\n\\s{4}${name}:\\s*\\{`).test(schema)) {
    console.log(`schema: ${name} already present, skip`);
  } else if (schema.includes('// <generated-resources>')) {
    const writableList = writable.map((w) => `'${w}'`).join(', ');
    const block =
      `    ${name}: {\n` +
      `      roles: {\n` +
      `        tenant_admin: { all: true },\n` +
      `        member: {\n` +
      `          select: ${selectExpr},\n` +
      `          insert: [${writableList}],\n` +
      `          update: [${writableList}],\n` +
      `          where: eqUser('owner_id'),\n` +
      `        },\n` +
      `      },\n` +
      `    },\n` +
      `    // <generated-resources>`;
    schema = schema.replace('    // <generated-resources>', block);
    writeFileSync(schemaPath, schema, 'utf8');
    console.log(`schema: added ${name}`);
  } else {
    console.warn('schema: marker <generated-resources> not found; add rules manually');
  }

  // 3) 后端路由 GET/POST/PATCH/DELETE
  const routePath = join(apiDir, 'src', 'routes', `${name}.ts`);
  const route = `import type { FastifyInstance } from 'fastify';

/** ${name}（generated by generate-resource） */
export function ${fn}(app: FastifyInstance): void {
  app.get(
    '/api/${name}',
    { preHandler: [app.rlsKit.authenticate, app.rlsKit.can('${name}', 'select')] },
    async (req) => {
      const rows = await app.rlsKit.withContext(req, async (c) => {
        const r = await c.query('select ${selCols.join(', ')} from public.${name} order by created_at desc');
        return r.rows;
      });
      return { code: 200, msg: 'success', data: rows };
    },
  );

  app.post(
    '/api/${name}',
    { preHandler: [app.rlsKit.authenticate, app.rlsKit.can('${name}', 'insert')] },
    async (req, reply) => {
      const ctx = app.rlsKit.ctx(req);
      const data = app.rlsKit.pick((req.body ?? {}) as Record<string, unknown>, '${name}', 'insert', ctx.role_type, { reject: true });
      const FIELDS = [${fields.map((f) => `'${f.name}'`).join(', ')}] as const;
      const cols = ['tenant_id'];
      const vals: unknown[] = [ctx.tenant_id];
      for (const f of FIELDS) {
        if (data[f] !== undefined) { cols.push(f); vals.push(data[f]); }
      }
      cols.push('owner_id');
      vals.push(ctx.user_id);
      const ph = cols.map((_, i) => \`$\${i + 1}\`).join(', ');
      const row = await app.rlsKit.withContext(req, async (c) => {
        const r = await c.query(
          \`insert into public.${name}(\${cols.join(', ')}) values (\${ph}) returning ${selCols.join(', ')}\`,
          vals,
        );
        await app.rlsKit.audit(c, req, { type: '新建${name}', sourceType: '${name}', sourceId: r.rows[0].id });
        return r.rows[0];
      });
      return { code: 200, msg: 'success', data: row };
    },
  );

  app.patch(
    '/api/${name}/:id',
    { preHandler: [app.rlsKit.authenticate, app.rlsKit.can('${name}', 'update')] },
    async (req, reply) => {
      const ctx = app.rlsKit.ctx(req);
      const id = (req.params as { id: string }).id;
      const data = app.rlsKit.pick((req.body ?? {}) as Record<string, unknown>, '${name}', 'update', ctx.role_type);
      const sets: string[] = [];
      const vals: unknown[] = [];
      const push = (col: string, val: unknown) => { vals.push(val); sets.push(\`\${col} = $\${vals.length}\`); };
${fields.map((f) => `      if (data.${f.name} !== undefined) push('${f.name}', data.${f.name} as never);`).join('\n')}
      if (!sets.length) return reply.code(400).send({ code: 400, msg: '无可更新字段', data: null });
      sets.push('version = version + 1');
      vals.push(id);
      const row = await app.rlsKit.withContext(req, async (c) => {
        const r = await c.query(\`update public.${name} set \${sets.join(', ')} where id = $\${vals.length} returning ${selCols.join(', ')}\`, vals);
        if (r.rowCount) await app.rlsKit.audit(c, req, { type: '编辑${name}', sourceType: '${name}', sourceId: id });
        return r.rows[0] ?? null;
      });
      if (!row) return reply.code(404).send({ code: 404, msg: '资源不存在或无权修改', data: null });
      return { code: 200, msg: 'success', data: row };
    },
  );

  app.delete(
    '/api/${name}/:id',
    { preHandler: [app.rlsKit.authenticate, app.rlsKit.can('${name}', 'delete')] },
    async (req, reply) => {
      const id = (req.params as { id: string }).id;
      const row = await app.rlsKit.withContext(req, async (c) => {
        const r = await c.query(\`delete from public.${name} where id = $1 returning id\`, [id]);
        if (r.rowCount) await app.rlsKit.audit(c, req, { type: '删除${name}', sourceType: '${name}', sourceId: id });
        return r.rows[0] ?? null;
      });
      if (!row) return reply.code(404).send({ code: 404, msg: '资源不存在或无权删除', data: null });
      return { code: 200, msg: 'success', data: row };
    },
  );
}
`;
  writeFileSync(routePath, route, 'utf8');
  console.log(`route: api/src/routes/${name}.ts`);

  // 4) server 注册（幂等）
  const serverPath = join(apiDir, 'src', 'server.ts');
  let server = readFileSync(serverPath, 'utf8');
  const importLine = `import { ${fn} } from './routes/${name}.ts';`;
  if (!server.includes(importLine)) {
    server = server.replace('// <generated:imports>', `${importLine}\n// <generated:imports>`);
    server = server.replace('// <generated:registers>', `${fn}(app);\n// <generated:registers>`);
    writeFileSync(serverPath, server, 'utf8');
    console.log(`server: registered ${fn}`);
  } else {
    console.log('server: already registered');
  }

  // 4b) 前端页 + Layout 注册（幂等）
  const pagePath = join(projectRoot, 'web', 'src', 'pages', `${pascalName}.tsx`);
  if (!existsSync(pagePath)) {
    const iface = fields.map((f) => `  ${f.name}?: string | number | null;`).join('\n');
    const statusField = fields.find((f) => f.name === 'status' && Array.isArray(f.enum));
    const colDefs = fields
      .map((f) => {
        if (f.name === 'status' && Array.isArray(f.enum)) {
          return `          { title: '${f.name}', dataIndex: '${f.name}', render: (v: string, row: Row) => (<Select size="small" value={v} style={{ width: 120 }} onChange={(s) => setStatus(row, s)} options={STATUS_OPTIONS} />) },`;
        }
        if (Array.isArray(f.enum)) {
          return `          { title: '${f.name}', dataIndex: '${f.name}', render: (v: string) => <Tag>{v}</Tag> },`;
        }
        return `          { title: '${f.name}', dataIndex: '${f.name}' },`;
      })
      .join('\n');
    const formItems = writable
      .map((w) => {
        const f = fields.find((x) => x.name === w) ?? { type: 'text' };
        const rules = f.required ? ` rules={[{ required: true, message: '必填' }]}` : '';
        if (Array.isArray(f.enum)) {
          return `          <Form.Item name="${w}" label="${w}"${rules}><Select options={[${f.enum.map((e) => `{ value: '${e}', label: '${e}' }`).join(', ')}]} /></Form.Item>`;
        }
        const comp = f.type === 'numeric' ? `<InputNumber style={{ width: '100%' }} />` : `<Input />`;
        return `          <Form.Item name="${w}" label="${w}"${rules}>${comp}</Form.Item>`;
      })
      .join('\n');
    const statusConst = statusField
      ? `const STATUS_OPTIONS = [${statusField.enum.map((e) => `{ value: '${e}', label: '${e}' }`).join(', ')}];\n\n`
      : '';
    const page = `import { useEffect, useState } from 'react';
import { Button, Form, Input, InputNumber, Modal, Popconfirm, Select, Space, Table, Tag, message } from 'antd';
import { api, errMsg, type Me } from '../api';

interface Row {
  id: string;
${iface}
  owner_id: string | null;
  version: number;
  created_at: string;
}

${statusConst}/** ${name}（generated by generate-resource） */
export default function ${pascalName}({ me }: { me?: Me }) {
  const isAdmin = me?.role_type === 'tenant_admin';
  const [rows, setRows] = useState<Row[]>([]);
  const [loading, setLoading] = useState(false);
  const [open, setOpen] = useState(false);
  const [editing, setEditing] = useState<Row | null>(null);
  const [form] = Form.useForm();
  const [q, setQ] = useState('');

  const load = async () => {
    setLoading(true);
    try {
      const res = await api.get('/${name}');
      setRows(res.data.data);
    } catch (e) {
      message.error(errMsg(e));
    } finally {
      setLoading(false);
    }
  };
  useEffect(() => { void load(); }, []);

  const openCreate = () => { setEditing(null); form.resetFields(); setOpen(true); };
  const openEdit = (row: Row) => { setEditing(row); form.setFieldsValue(row); setOpen(true); };

  const submit = async () => {
    const values = await form.validateFields();
    try {
      if (editing) { await api.patch(\`/${name}/\${editing.id}\`, values); message.success('已更新'); }
      else { await api.post('/${name}', values); message.success('已创建'); }
      setOpen(false); form.resetFields(); setEditing(null); void load();
    } catch (e) {
      message.error(errMsg(e));
    }
  };

  const remove = async (row: Row) => {
    try { await api.delete(\`/${name}/\${row.id}\`); message.success('已删除'); void load(); }
    catch (e) { message.error(errMsg(e)); }
  };

  const setStatus = async (row: Row, status: string) => {
    try { await api.patch(\`/${name}/\${row.id}\`, { status }); message.success('已更新'); void load(); }
    catch (e) { message.error(errMsg(e)); }
  };

  return (
    <>
      <Space style={{ marginBottom: 16 }}>
        <Button type="primary" onClick={openCreate}>新建</Button>
        <Input.Search placeholder="搜索" allowClear style={{ width: 240 }} value={q} onChange={(e) => setQ(e.target.value)} />
      </Space>
      <Table
        rowKey="id"
        loading={loading}
        dataSource={q ? rows.filter((r) => JSON.stringify(r).toLowerCase().includes(q.toLowerCase())) : rows}
        pagination={{ pageSize: 10, showSizeChanger: true }}
        columns={[
${colDefs}
          { title: '归属', dataIndex: 'owner_id', render: (v: string | null) => v ?? '-' },
          { title: '时间', dataIndex: 'created_at', render: (v: string) => new Date(v).toLocaleString() },
          {
            title: '操作',
            render: (_v: unknown, row: Row) => (
              <Space>
                <Button size="small" type="link" onClick={() => openEdit(row)}>编辑</Button>
                {isAdmin && (
                  <Popconfirm title="确认删除？" onConfirm={() => remove(row)}>
                    <Button size="small" type="link" danger>删除</Button>
                  </Popconfirm>
                )}
              </Space>
            ),
          },
        ]}
      />
      <Modal open={open} title={editing ? '编辑' : '新建'} onOk={submit} onCancel={() => setOpen(false)}>
        <Form form={form} layout="vertical">
${formItems}
        </Form>
      </Modal>
    </>
  );
}
`;
    writeFileSync(pagePath, page, 'utf8');
    console.log(`page: web/src/pages/${pascalName}.tsx`);
  } else {
    console.log(`page: ${pascalName}.tsx already exists, skip`);
  }

  const layoutPath = join(projectRoot, 'web', 'src', 'pages', 'Layout.tsx');
  if (existsSync(layoutPath)) {
    let layout = readFileSync(layoutPath, 'utf8');
    const webImport = `import ${pascalName} from './${pascalName}';`;
    if (!layout.includes(webImport) && layout.includes('// <generated:web-imports>')) {
      layout = layout
        .replace('// <generated:web-imports>', `${webImport}\n// <generated:web-imports>`)
        .replace(
          '// <generated:menu>',
          `{ key: '/app/${name}', icon: <AppstoreOutlined />, label: '${pascalName}' },\n    // <generated:menu>`,
        )
        .replace(
          '{/* <generated:web-routes> */}',
          `<Route path="/app/${name}" element={<${pascalName} me={me} />} />\n            {/* <generated:web-routes> */}`,
        );
      writeFileSync(layoutPath, layout, 'utf8');
      console.log(`layout: registered /app/${name}`);
    } else {
      console.log('layout: already registered');
    }
  }

  // 5) 生成 RLS（依赖项目已 npm install）
  console.log('\ngenerating RLS migration ...');
  const r = spawnSync(`npm run generate:rls -- --table ${name}`, { cwd: apiDir, stdio: 'inherit', shell: true });
  if (r.status !== 0) {
    console.warn('\nRLS generation skipped (run manually): cd api && npm run generate:rls -- --table ' + name);
  }

  console.log(`\nDone. Next:
  cd api && npx tsc --noEmit
  cd ../web && npx tsc --noEmit
  docker compose up -d --build`);
}

main();
