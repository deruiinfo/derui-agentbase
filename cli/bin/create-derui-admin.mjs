#!/usr/bin/env node
/**
 * create-derui-admin — 从 template/ 生成一个自托管单租户后台工程，并按项目名做品牌替换。
 *
 * 用法：
 *   node cli/bin/create-derui-admin.mjs <target-dir> [--name <name>] [--port <webPort>] [--force]
 *   npx create-derui-admin my-admin --name "My Admin" --port 8080
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  copyFileSync,
  readFileSync,
  writeFileSync,
  statSync,
} from 'node:fs';
import { resolve, join, dirname, basename, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';

const __dirname = dirname(fileURLToPath(import.meta.url));
const TEMPLATE_DIR = resolve(__dirname, '../../template');

const SKIP_DIRS = new Set(['node_modules', 'data', 'dist', '.git']);
const SKIP_FILES = new Set(['package-lock.json']);
// 仅对这些文本扩展名做替换（跳过 .tgz/.png 等二进制）
const TEXT_EXTS = new Set([
  '.ts', '.tsx', '.js', '.mjs', '.json', '.html', '.yml', '.yaml',
  '.md', '.conf', '.sql', '.sh', '.example', '.env', '.gitignore', '',
]);

function parseArgs(argv) {
  const args = { target: null, name: null, port: 8080, force: false };
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--name') args.name = argv[++i];
    else if (a === '--port') args.port = Number(argv[++i]);
    else if (a === '--force') args.force = true;
    else if (a === '-h' || a === '--help') args.help = true;
    else rest.push(a);
  }
  args.target = rest[0] ?? null;
  if (!args.name && args.target) args.name = basename(resolve(args.target));
  return args;
}

function usage() {
  console.log(`create-derui-admin — generate a self-hosted admin scaffold

Usage:
  create-derui-admin <target-dir> [--name <name>] [--port <webPort>] [--force]

Options:
  --name   project/brand name (default: target dir name)
  --port   web port (default: 8080)
  --force  allow non-empty target directory
`);
}

function slugify(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'app';
}

function copyDir(src, dest) {
  mkdirSync(dest, { recursive: true });
  for (const entry of readdirSync(src, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      copyDir(join(src, entry.name), join(dest, entry.name));
    } else if (entry.isFile()) {
      if (SKIP_FILES.has(entry.name)) continue;
      copyFileSync(join(src, entry.name), join(dest, entry.name));
    }
  }
}

/** 对文本文件做品牌替换 */
function brandify(dir, map) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      brandify(p, map);
    } else if (entry.isFile()) {
      if (!TEXT_EXTS.has(extname(entry.name)) && entry.name !== '.gitignore') continue;
      let text = readFileSync(p, 'utf8');
      let changed = false;
      for (const [from, to] of map) {
        if (text.includes(from)) {
          text = text.split(from).join(to);
          changed = true;
        }
      }
      if (changed) writeFileSync(p, text, 'utf8');
    }
  }
}

function buildEnv(name, port) {
  const pg = randomBytes(16).toString('hex');
  const app = randomBytes(16).toString('hex');
  const jwt = randomBytes(32).toString('hex');
  return `# generated by create-derui-admin
POSTGRES_PASSWORD=${pg}
POSTGRES_DB=app
APP_DB_ROLE=app_user
APP_DB_PASSWORD=${app}
DATABASE_URL_ADMIN=postgres://postgres:${pg}@db:5432/app
DATABASE_URL_APP=postgres://app_user:${app}@db:5432/app
APP_JWT_SECRET=${jwt}
APP_JWT_EXPIRE_HOURS=2
ADMIN_ACCOUNT=admin
ADMIN_PASSWORD=change-me
DEFAULT_TENANT_NAME=${name}
LOGIN_MAX_FAIL=5
LOGIN_LOCK_MINUTES=30
DB_PORT=5432
API_PORT=3001
WEB_PORT=${port}
`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help || !args.target) {
    usage();
    process.exit(args.target ? 0 : 1);
  }
  if (!existsSync(TEMPLATE_DIR)) {
    console.error(`template not found: ${TEMPLATE_DIR}`);
    process.exit(1);
  }

  const target = resolve(args.target);
  if (existsSync(target)) {
    if (readdirSync(target).length > 0 && !args.force) {
      console.error(`target not empty: ${target} (use --force to override)`);
      process.exit(1);
    }
  }

  const slug = slugify(args.name);
  console.log(`[create-derui-admin] template: ${TEMPLATE_DIR}`);
  console.log(`[create-derui-admin] target:   ${target}`);
  console.log(`[create-derui-admin] name:     ${args.name}  (slug: ${slug})`);

  copyDir(TEMPLATE_DIR, target);

  // 品牌替换
  brandify(target, [
    ['Admin Console', args.name],
    ['admin-scaffold-api', `${slug}-api`],
    ['admin-scaffold-web', `${slug}-web`],
    ['name: admin-scaffold', `name: ${slug}`],
  ]);

  writeFileSync(join(target, '.env'), buildEnv(args.name, args.port), 'utf8');

  console.log(`\nDone. Next:\n  cd ${target}\n  docker compose up -d --build\n`);
  console.log(`  web:      http://127.0.0.1:${args.port}`);
  console.log(`  account:  admin / change-me (see .env)\n`);
}

main();
